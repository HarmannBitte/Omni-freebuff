// Mock freebuff2api: mirrors the REAL freebuff2api surface
// (https://github.com/yuzu-octopus/freebuff2api) without needing Bun,
// a FreeBuff token, or network access to codebuff.com.
//
//   node mock-freebuff2api.mjs   → http://127.0.0.1:8787
//
// Faithful bits:
//   GET  /health[?verbose=1]   tokens + tokensDetail + streak
//   GET  /v1/streak             quota status passthrough shape
//   POST /v1/token-count        server-side token meter shape
//   GET  /v1/models             catalog + live quota enrichment
//   POST /v1/chat/completions   OpenAI shape; unlimited flash/mimo,
//                               premium pool (6/day real; 2/demo-run here)
//                               → 429 relay when spent, like the real router.
//   Protocol log lines mimic: Pool.acquire → session admit → START run → chat → FINISH.
import http from "node:http";

const PORT = 8787;
const TOKEN = process.env.FREEBUFF_TOKEN ?? "mock-token";
const TOKENS = TOKEN.split(",").map((t) => t.trim()).filter(Boolean);

// Demo quotas: flash/mimo unlimited (like prod); premium capped low so the
// demo can show a 429 relay without burning 6 real sessions.
const CATALOG = [
  { id: "deepseek/deepseek-v4-flash", display: "DeepSeek V4 Flash", quota: "unlimited", type: "unlimited", context_window: 1048576, max_output_tokens: 32768, demoQuota: Infinity },
  { id: "mimo/mimo-v2.5", display: "MiMo 2.5", quota: "unlimited", type: "unlimited", context_window: 131072, max_output_tokens: 32768, demoQuota: Infinity },
  { id: "deepseek/deepseek-v4-pro", display: "DeepSeek V4 Pro", quota: "6/day", type: "premium", context_window: 131072, max_output_tokens: 32768, demoQuota: 2 },
  { id: "minimax/minimax-m3", display: "MiniMax M3", quota: "6/day", type: "premium", context_window: 524288, max_output_tokens: 32768, demoQuota: 2 },
  { id: "openai/gpt-5.6-luna", display: "GPT-5.6 Luna", quota: "6/day", type: "premium", context_window: 1000000, max_output_tokens: 32768, demoQuota: 2 },
  { id: "z-ai/glm-5.2", display: "GLM 5.2", quota: "referral-gated", type: "referral", context_window: 131072, max_output_tokens: 32768, demoQuota: 0 },
];
const used = Object.fromEntries(CATALOG.map((m) => [m.id, 0]));
let runSeq = 0;

function planNextStep(messages) {
  const lastUser = [...messages].reverse().find((m) => m.role === "user");
  const text = typeof lastUser?.content === "string" ? lastUser.content : JSON.stringify(lastUser?.content ?? "");
  const m = text.match(/PENDING_TASKS_JSON:\s*(\[.*?\])/s);
  let pending = [];
  try { pending = JSON.parse(m?.[1] ?? "[]"); } catch { pending = []; }
  if (!pending.length) return { done: true, note: "no pending tasks" };
  const t = pending[0];
  return {
    done: false,
    step: t.id,
    title: t.title,
    file: t.file,
    content:
      `// ${t.title}\n` +
      `// generated by freebuff tier (mock ${"flash"})\n` +
      `// hint: ${t.hint ?? "n/a"}\n` +
      `export const ${t.id.replace(/-/g, "_")} = ${JSON.stringify(t.title)};\n`,
    note: `picked ${t.id} (${pending.length - 1} remaining after this)`,
  };
}

const server = http.createServer((req, res) => {
  const url = new URL(req.url, `http://127.0.0.1:${PORT}`);
  res.setHeader("X-Mock-Upstream", "freebuff-mock");

  if (req.method === "GET" && url.pathname === "/health") {
    const verbose = url.searchParams.get("verbose") === "1";
    const body = { status: "ok", tokens: TOKENS.length };
    if (verbose) {
      body.tokensDetail = TOKENS.map((t) => ({
        token: t.length > 8 ? `${t.slice(0, 4)}…${t.slice(-4)}` : "***",
        busy: false, sessionModel: "deepseek/deepseek-v4-flash", toolQuotaExhausted: false,
      }));
      body.streak = { streak: 7, todayUsed: 2, lastResetMultiplier: 1, note: "mock" };
    }
    res.writeHead(200, { "Content-Type": "application/json" });
    res.end(JSON.stringify(body));
    return;
  }

  if (req.method === "GET" && (url.pathname === "/v1/streak" || url.pathname === "/streak")) {
    res.writeHead(200, { "Content-Type": "application/json" });
    res.end(JSON.stringify({ streak: 7, todayUsed: 2, lastResetMultiplier: 1, note: "mock" }));
    return;
  }

  if (req.method === "POST" && (url.pathname === "/v1/token-count" || url.pathname === "/token-count")) {
    let raw = "";
    req.on("data", (c) => (raw += c));
    req.on("end", () => {
      res.writeHead(200, { "Content-Type": "application/json" });
      res.end(JSON.stringify({ inputTokens: Math.ceil(raw.length / 4), note: "mock" }));
    });
    return;
  }

  if (req.method === "GET" && url.pathname === "/v1/models") {
    const now = Math.floor(Date.now() / 1000);
    const data = CATALOG.map((m) => ({
      id: m.id, object: "model", created: now, owned_by: "freebuff",
      display: m.display, display_name: m.display,
      context_window: m.context_window, max_output_tokens: m.max_output_tokens,
      quota: m.quota, type: m.type,
      ...(m.demoQuota !== Infinity
        ? { userRemaining: Math.max(0, m.demoQuota - used[m.id]), userResetAt: "midnight PT (mock)" }
        : { userRemaining: "unlimited" }),
    }));
    res.writeHead(200, { "Content-Type": "application/json" });
    res.end(JSON.stringify({ object: "list", data }));
    return;
  }

  if (req.method === "POST" && url.pathname === "/v1/chat/completions") {
    let raw = "";
    req.on("data", (c) => (raw += c));
    req.on("end", () => {
      let body = {};
      try { body = JSON.parse(raw); } catch {}
      const model = body.model ?? "deepseek/deepseek-v4-flash";
      const entry = CATALOG.find((m) => m.id === model);

      const runId = `run-mock-${++runSeq}`;
      console.log(`[freebuff-mock] Pool.acquire(${model}) → token#1`);
      console.log(`[freebuff-mock] POST /api/v1/freebuff/session → active (mock admit)`);
      console.log(`[freebuff-mock] POST /api/v1/agent-runs START → ${runId}`);

      if (!entry) {
        res.writeHead(404, { "Content-Type": "application/json" });
        res.end(JSON.stringify({ error: { type: "not_found", message: `Model \`${model}\` is unavailable`, param: "model" } }));
        return;
      }
      if (used[model] >= entry.demoQuota) {
        // Real router relays upstream 429s as-is (except tool-bucket failover).
        res.writeHead(429, { "Content-Type": "application/json", "Retry-After": "60" });
        res.end(JSON.stringify({
          error: { type: "rate_limit_error", message: `Freebuff ${model}: daily free sessions spent (mock of 6/day pool).` },
        }));
        console.log(`[freebuff-mock] 429 premium pool spent for ${model}`);
        return;
      }
      used[model]++;
      const action = planNextStep(body.messages ?? []);
      if (action.file) {
        action.content = action.content.replace("mock flash", `mock ${entry.display}`);
      }
      const payload = {
        id: `chatcmpl-fbmock-${runSeq}`,
        object: "chat.completion",
        created: Math.floor(Date.now() / 1000),
        model,
        choices: [{ index: 0, message: { role: "assistant", content: JSON.stringify(action) }, finish_reason: "stop" }],
        usage: { prompt_tokens: 140, completion_tokens: 70, total_tokens: 210 },
      };
      res.writeHead(200, { "Content-Type": "application/json", "X-Mock-Upstream": "freebuff-mock" });
      res.end(JSON.stringify(payload));
      console.log(`[freebuff-mock] chat → ${action.step ?? "done"} via ${model} (used=${used[model]}) → FINISH ${runId}`);
    });
    return;
  }

  res.writeHead(404, { "Content-Type": "application/json" });
  res.end(JSON.stringify({ error: { message: "not found (mock)" } }));
});

server.listen(PORT, "127.0.0.1", () => {
  console.log(`[mock] freebuff2api-mock → http://127.0.0.1:${PORT}  tokens=${TOKENS.length}`);
  console.log(`[mock] unlimited: deepseek-v4-flash, mimo-v2.5 | premium demo-quota: 2/run`);
});
