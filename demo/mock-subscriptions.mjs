// Mock subscription providers: behave like Claude Code / Codex OAuth subs.
// Each serves N requests, then returns 429 (simulating the 5-hour window
// cap) for the rest of the demo run.
//
//   node mock-subscriptions.mjs
//   → claude-sub on 127.0.0.1:8891  (model cc/claude-opus-4-6, quota: 3)
//   → codex-sub   on 127.0.0.1:8892  (model cx/gpt-5.2-codex,  quota: 2)
//
// OpenAI-compatible: GET /health, GET /v1/models, POST /v1/chat/completions
import http from "node:http";

function makeMock({ name, port, modelId, quota, resetHint }) {
  let used = 0;

  function planNextStep(messages) {
    // Find the machine-readable pending list the agent embeds in its prompt.
    const lastUser = [...messages].reverse().find((m) => m.role === "user");
    const text = typeof lastUser?.content === "string" ? lastUser.content : JSON.stringify(lastUser?.content ?? "");
    const m = text.match(/PENDING_TASKS_JSON:\s*(\[.*?\])/s);
    let pending = [];
    try { pending = JSON.parse(m?.[1] ?? "[]"); } catch { pending = []; }
    if (!pending.length) return { done: true, note: "no pending tasks" };
    const t = pending[0];
    return {
      done: false,
      step: t.id,
      title: t.title,
      file: t.file,
      content:
        `// ${t.title}\n` +
        `// generated by ${modelId} via ${name}\n` +
        `// hint: ${t.hint ?? "n/a"}\n` +
        `export const ${t.id.replace(/-/g, "_")} = ${JSON.stringify(t.title)};\n`,
      note: `picked ${t.id} (${pending.length - 1} remaining after this)`,
    };
  }

  const server = http.createServer((req, res) => {
    const url = new URL(req.url, `http://127.0.0.1:${port}`);
    res.setHeader("X-Mock-Upstream", name);

    if (req.method === "GET" && url.pathname === "/health") {
      res.writeHead(200, { "Content-Type": "application/json" });
      res.end(JSON.stringify({ status: "ok", upstream: name, used, quota }));
      return;
    }
    if (req.method === "GET" && url.pathname === "/v1/models") {
      res.writeHead(200, { "Content-Type": "application/json" });
      res.end(JSON.stringify({
        object: "list",
        data: [{ id: modelId, object: "model", owned_by: name, quota: `${quota - used} left` }],
      }));
      return;
    }
    if (req.method === "POST" && url.pathname === "/v1/chat/completions") {
      let raw = "";
      req.on("data", (c) => (raw += c));
      req.on("end", () => {
        if (used >= quota) {
          // Simulate the subscription window cap (e.g. Claude 5-hour limit).
          res.writeHead(429, {
            "Content-Type": "application/json",
            "Retry-After": "300",
            "X-Mock-Upstream": name,
          });
          res.end(JSON.stringify({
            error: {
              type: "rate_limit_error",
              code: "subscription_window_exhausted",
              message: `${name}: 5-hour subscription window exhausted (${resetHint}).`,
            },
          }));
          console.log(`[${name}] 429 window-exhausted (used=${used}/${quota})`);
          return;
        }
        used++;
        let body = {};
        try { body = JSON.parse(raw); } catch {}
        const action = planNextStep(body.messages ?? []);
        const payload = {
          id: `chatcmpl-mock-${name}-${used}`,
          object: "chat.completion",
          created: Math.floor(Date.now() / 1000),
          model: modelId,
          choices: [{ index: 0, message: { role: "assistant", content: JSON.stringify(action) }, finish_reason: "stop" }],
          usage: { prompt_tokens: 120, completion_tokens: 60, total_tokens: 180 },
        };
        res.writeHead(200, { "Content-Type": "application/json", "X-Mock-Upstream": name });
        res.end(JSON.stringify(payload));
        console.log(`[${name}] 200 served ${action.step ?? "done"} (used=${used}/${quota})`);
      });
      return;
    }
    res.writeHead(404, { "Content-Type": "application/json" });
    res.end(JSON.stringify({ error: { message: "not found" } }));
  });

  server.listen(port, "127.0.0.1", () =>
    console.log(`[mock] ${name} → http://127.0.0.1:${port}  model=${modelId} quota=${quota}`)
  );
}

makeMock({ name: "claude-sub", port: 8891, modelId: "cc/claude-opus-4-6", quota: 3, resetHint: "resets in ~5h" });
makeMock({ name: "codex-sub", port: 8892, modelId: "cx/gpt-5.2-codex", quota: 2, resetHint: "resets in ~5h" });
